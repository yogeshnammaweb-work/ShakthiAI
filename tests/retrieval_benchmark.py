import json
from fastembed import TextEmbedding
import chromadb

DATA = r"data\master_dataset\StudentModules_chunks.jsonl"

# These questions must be answerable from the StudentModules content.
queries = [
    "????? ??????? ?????? ????????",
    "????????? ??? ????? ????? ????? ????????? ???????????",
    "18 ?????????? ????? ???????? ??? ?????? ?????? ?????????",
    "????????? ????? ???????? ??? ??????",
    "???????? ???????? ???????????? ??????? ????????? ????????",
    "????? ???? ?????? ?????? ????????????? ?????? ??? ??????????",
    "?????????? ????? ?????? ???? ???????",
    "???????? ??????, ?????? ????? ????? ??????? ???????????",
]

with open(DATA, encoding="utf-8") as f:
    rows = [json.loads(line) for line in f]

documents = [r["text"] for r in rows]
ids = [r["chunk_id"] for r in rows]

models = [
    "BAAI/bge-small-en-v1.5",
    "sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2",
]

for model_name in models:
    print("\n" + "=" * 80)
    print("MODEL:", model_name)
    print("=" * 80)

    embedder = TextEmbedding(model_name=model_name)

    client = chromadb.EphemeralClient()
    collection = client.create_collection(name="benchmark_" + model_name.replace("/", "_").replace("-", "_"))

    doc_embeddings = [
        list(embedder.embed([doc]))[0].tolist()
        for doc in documents
    ]

    collection.add(
        ids=ids,
        documents=documents,
        embeddings=doc_embeddings,
    )

    for query in queries:
        query_embedding = list(
            embedder.embed([query])
        )[0].tolist()

        result = collection.query(
            query_embeddings=[query_embedding],
            n_results=2,
        )

        print("\nQUERY:", query)

        for rank in range(2):
            chunk_id = result["ids"][0][rank]
            distance = result["distances"][0][rank]
            text = result["documents"][0][rank]

            page = next(
                r["page"] for r in rows
                if r["chunk_id"] == chunk_id
            )

            print(
                f"  Rank {rank + 1} | "
                f"{chunk_id} | page {page} | "
                f"distance {distance:.6f}"
            )
            print("  ", text[:250].replace("\n", " "))

